/**
 * One-time seed v3: 10 commercial + informational blog posts.
 */
function liderdent_run_content_seed_v3(): void {
	if ( get_option( 'liderdent_content_seed_v3' ) ) {
		return;
	}
	if ( ! function_exists( 'wp_insert_post' ) ) {
		return;
	}

	if ( ! function_exists( 'wp_get_current_user' ) || ! current_user_can( 'upload_files' ) ) {
		wp_set_current_user( 1 );
	}

	$blog    = get_category_by_slug( 'blog' );
	$blog_id = $blog ? (int) $blog->term_id : 0;
	$pending = false;

	foreach ( liderdent_content_seed_posts_v3() as $post ) {
		$existing = get_posts(
			[
				'name'           => $post['slug'],
				'post_type'      => 'post',
				'post_status'    => 'any',
				'posts_per_page' => 1,
				'fields'         => 'ids',
			]
		);
		if ( $existing ) {
			continue;
		}

		$post_id = wp_insert_post(
			[
				'post_title'   => $post['title'],
				'post_name'    => $post['slug'],
				'post_content' => $post['content'],
				'post_excerpt' => $post['excerpt'],
				'post_status'  => 'publish',
				'post_author'  => 1,
				'post_type'    => 'post',
			],
			true
		);
		if ( is_wp_error( $post_id ) || ! $post_id ) {
			$pending = true;
			continue;
		}

		if ( $blog_id ) {
			wp_set_post_categories( (int) $post_id, [ $blog_id ] );
		}

		$att = liderdent_sideload_theme_attachment( $post['image'], $post['title'] );
		if ( $att ) {
			set_post_thumbnail( (int) $post_id, $att );
		} else {
			$pending = true;
		}
	}

	if ( ! $pending ) {
		update_option( 'liderdent_content_seed_v3', 1, false );
		if ( function_exists( 'wp_cache_flush' ) ) {
			wp_cache_flush();
		}
	}
}
add_action( 'init', 'liderdent_run_content_seed_v3', 44 );

