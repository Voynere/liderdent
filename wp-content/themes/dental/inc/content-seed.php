		$content = (string) get_post_field( 'post_content', $post_id );
		if ( str_contains( $content, 'article-figure--seed' ) ) {
			continue;
		}

		$att = liderdent_sideload_theme_attachment( $item['image'], $item['alt'] );
		if ( ! $att ) {
			$pending = true;
			continue;
		}

		$url = wp_get_attachment_image_url( $att, 'large' );
		if ( ! $url ) {
			$pending = true;
			continue;
		}

		$figure = sprintf(
			'<figure class="article-figure article-figure--seed"><img src="%s" alt="%s" loading="lazy" decoding="async" /><figcaption class="article-figure__caption">%s</figcaption></figure>',
			esc_url( $url ),
			esc_attr( $item['alt'] ),
			esc_html( $item['caption'] )
		);

		$new_content = liderdent_insert_figure_after_first_h2( $content, $figure );
		$updated     = wp_update_post(
			[
				'ID'           => $post_id,
				'post_content' => $new_content,
			],
			true
		);
		if ( is_wp_error( $updated ) ) {
			$pending = true;
		}
	}

	if ( ! $pending ) {
		update_option( 'liderdent_blog_inline_seed_v1', 1, false );
		if ( function_exists( 'wp_cache_flush' ) ) {
			wp_cache_flush();
		}
	}
}
add_action( 'init', 'liderdent_run_blog_inline_images_seed', 42 );

/**
 * One-time: published posts keep the old braces promo after the theme price change.
 */
function liderdent_sync_braces_promo_215k(): void {
	if ( get_option( 'liderdent_braces_promo_215k_v1' ) ) {
		return;
	}
	if ( ! function_exists( 'wp_update_post' ) ) {
		return;
	}

	$slugs = [
		'brekety-pod-klyuch-200000-chto-vhodit-v-programmu',
		'skolko-nosit-brekety-sroki-lecheniya',
		'rassrochka-na-stomatologiyu-v-liderdent',
	];
	$replace = [
		'200&nbsp;000'  => '215&nbsp;000',
		'200 000'       => '215 000',
		'до 31.08.2026' => 'до 31.10.2026',
		'до 30.09.2026' => 'до 31.10.2026',
	];

	foreach ( $slugs as $slug ) {
		$existing = get_posts(
			[
				'name'           => $slug,
				'post_type'      => 'post',
				'post_status'    => 'any',
				'posts_per_page' => 1,
				'fields'         => 'ids',
			]
		);
		if ( ! $existing ) {
			continue;
		}

		$post = get_post( (int) $existing[0] );
		if ( ! $post ) {
			continue;
		}

		$title   = strtr( $post->post_title, $replace );
		$content = strtr( $post->post_content, $replace );
		if ( $title === $post->post_title && $content === $post->post_content ) {
			continue;
		}

		$updated = wp_update_post(
			[
				'ID'           => $post->ID,
				'post_title'   => $title,
				'post_content' => $content,
			],
			true
		);
		if ( is_wp_error( $updated ) ) {
			return;
		}
	}

	update_option( 'liderdent_braces_promo_215k_v1', 1, false );
}
add_action( 'init', 'liderdent_sync_braces_promo_215k', 50 );
