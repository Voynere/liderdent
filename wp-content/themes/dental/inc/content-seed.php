function liderdent_sideload_theme_attachment( string $relative_theme_path, string $title ): int {
	$abs = get_template_directory() . '/' . ltrim( $relative_theme_path, '/' );
	if ( ! file_exists( $abs ) ) {
		return 0;
	}

	require_once ABSPATH . 'wp-admin/includes/file.php';
	require_once ABSPATH . 'wp-admin/includes/media.php';
	require_once ABSPATH . 'wp-admin/includes/image.php';

	$tmp = wp_tempnam( basename( $abs ) );
	if ( ! $tmp || ! copy( $abs, $tmp ) ) {
		return 0;
	}

	$file_array = [
		'name'     => basename( $abs ),
		'tmp_name' => $tmp,
	];

	$id = media_handle_sideload( $file_array, 0, $title );
	if ( is_wp_error( $id ) ) {
		@unlink( $tmp );
		return 0;
	}
	return (int) $id;
}

function liderdent_run_content_seed(): void {
	if ( get_option( 'liderdent_content_seed_v1' ) ) {
		return;
	}
	if ( ! function_exists( 'wp_insert_post' ) ) {
		return;
	}

	// Sideload requires capability context on some hosts.
	if ( ! function_exists( 'wp_get_current_user' ) || ! current_user_can( 'upload_files' ) ) {
		wp_set_current_user( 1 );
	}

	$blog = get_category_by_slug( 'blog' );
	$blog_id = $blog ? (int) $blog->term_id : 0;

	foreach ( liderdent_content_seed_posts() as $post ) {
		$existing = get_posts(
			[
				'name'           => $post['slug'],
				'post_type'      => 'post',
				'post_status'    => 'any',
				'posts_per_page' => 1,
				'fields'         => 'ids',
			]
		);
		if ( $existing ) {
			continue;
		}

		$post_id = wp_insert_post(
			[
				'post_title'   => $post['title'],
				'post_name'    => $post['slug'],
				'post_content' => $post['content'],
				'post_excerpt' => $post['excerpt'],
				'post_status'  => 'publish',
				'post_type'    => 'post',
				'post_author'  => 1,
			],
			true
		);
		if ( is_wp_error( $post_id ) || ! $post_id ) {
			continue;
		}

		if ( $blog_id ) {
			wp_set_post_categories( (int) $post_id, [ $blog_id ] );
		}

		$att = liderdent_sideload_theme_attachment( $post['image'], $post['title'] );
		if ( $att ) {
			set_post_thumbnail( (int) $post_id, $att );
		}
	}

	// Sync category descriptions from theme texts (unique content).
	if ( function_exists( 'liderdent_get_services_content' ) ) {
		foreach ( liderdent_get_services_content() as $slug => $item ) {
			$term = get_term_by( 'slug', $slug, 'category' );
			if ( ! $term || is_wp_error( $term ) ) {
				continue;
			}
			wp_update_term(
				(int) $term->term_id,
				'category',
				[ 'description' => $item['html'] ]
			);
		}
	}

	update_option( 'liderdent_content_seed_v1', 1, false );
	if ( function_exists( 'wp_cache_flush' ) ) {
		wp_cache_flush();
	}
}
add_action( 'init', 'liderdent_run_content_seed', 40 );

