function liderdent_get_service_content( string $slug ): ?array {
	$map = liderdent_get_services_content();
	return $map[ $slug ] ?? null;
}

/**
 * HTML-описание категории услуг из темы.
 */
function liderdent_service_description_html( string $slug ): string {
	$item = liderdent_get_service_content( $slug );
	return $item['html'] ?? '';
}

/**
 * URL обложки услуги из темы (если есть).
 */
function liderdent_service_image_url( string $slug ): string {
	$item = liderdent_get_service_content( $slug );
	if ( ! $item || empty( $item['image'] ) ) {
		return '';
	}
	$path = get_template_directory() . '/' . $item['image'];
	if ( ! file_exists( $path ) ) {
		return '';
	}
	return get_template_directory_uri() . '/' . $item['image'];
}
